#!/usr/bin/env python3
"""Turn the D3V firmware image into re-assemblable, relocatable source.

    python3 kit/split.py [image.bin] -> build/app.s + build/dsp/*.bin

Every branch, literal load, code/data pointer, switch table and the pow() table
offsets are emitted symbolically, so code and data may grow or move.
"""
import sys
from pathlib import Path
from analyze import Image, BASE, ROOT, FW, REGION_TABLE

OUT = ROOT / 'build'
NOT_POINTERS = {0x2178}                       # 0x5AA5 = SYS_PORCTL key, not a code address
DATA_PTRS = {0x2740, 0x2744, 0x29a0, 0x2bb4, 0x372c, 0x3810,
             0x42ac, 0x42b4, 0x42bc, 0x42c0, 0x42c4, 0x7538, 0x7548, 0x7544, 0x7554}
# (first, end) of the five ADAU1701 download blocks, in the order the MCU sends them
DSP = {'seg0_ctrl_mute': (0x5ccc, 0x5cd0), 'seg3_ctrl_regs': (0x5cd0, 0x5cea),
       'seg4_ctrl_run': (0x5cea, 0x5cee), 'seg1_program': (0x5cee, 0x703c),
       'seg2_params': (0x703c, 0x74a2)}
LENGTHS = {0x42b0: ('dsp_seg1_program_end', 'dsp_seg1_program'),
           0x42b8: ('dsp_seg2_params_end', 'dsp_seg2_params'),
           0x7540: ('_image_end', 'data_init')}
KNOWN_PADS = {0x74a2: 8}                      # zero fill up to the 8-aligned pow() tables
TAIL = 0x5c54                                 # start of .constdata


def load_names():
    n = {}
    for line in (Path(__file__).parent / 'symbols.txt').read_text().splitlines():
        line = line.split('#')[0].split()
        if len(line) >= 2:
            n[int(line[0], 16)] = line[1]
    return n


def main():
    im = Image(im_path(None))
    names = load_names()
    lab, align = {}, {}

    def L(a, pfx):
        if a not in lab:
            lab[a] = names.get(a) or '%s_%04x' % (pfx, a)
        return lab[a]

    for i in im.ins.values():
        if i.kind in ('b', 'bcond'):
            L(i.target, 'loc')
        elif i.kind == 'bl':
            L(i.target, 'sub')
    for i in im.ins.values():
        if i.kind == 'ldrpc':
            L(i.target, 'lit')
        elif i.kind == 'adr':
            L(i.target, 'adr'); align[i.target] = 4
    for name, (s, e) in DSP.items():
        lab[s] = 'dsp_' + name
    lab[0x7558] = 'data_init'
    lab[REGION_TABLE[0]] = 'region_table'

    words = {}                                # addr -> expression
    wkind = {}                                # addr -> ('abs'|'thumb'|'len'|'pic', ...) for the verifier
    for a in range(BASE, BASE + 0xc0, 4):
        words[a] = '0x%08x' % im.u32(a)
    for a in range(REGION_TABLE[0], REGION_TABLE[1], 4):
        words[a] = '0x%08x' % im.u32(a)
    for a in im.lit:
        words[a] = '0x%08x' % im.u32(a)
    for a in sorted(im.code_ptr_words - NOT_POINTERS):
        v = im.u32(a)
        if v & 1:
            words[a] = 'ABS(%s) + 1' % L(v - 1, 'sub'); wkind[a] = ('thumb', v - 1)
    for a in DATA_PTRS:
        v = im.u32(a)
        words[a] = 'ABS(%s)' % ('_image_end' if v == im.end else L(v, 'dat')); wkind[a] = ('abs', v)
    for a, (hi, lo) in LENGTHS.items():
        words[a] = '%s - %s' % (hi, lo); wkind[a] = ('len', im.u32(a))
    # pow(): `ldr rX, =off ; add rX, pc`  ->  off = table - (anchor + 4)
    for a, i in im.ins.items():
        if i.text.startswith('.inst.n 0x447'):
            r, b = int(i.text[-1], 16) & 7, a
            while not (b in im.ins and im.ins[b].kind == 'ldrpc' and im.ins[b].text.startswith('ldr r%d,' % r)):
                b -= 2
            lit = im.ins[b].target
            words[lit] = '%s - (%s + 4)' % (L((a + 4 + im.u32(lit)) & 0xffffffff, 'dat'), L(a, 'pic'))
            wkind[lit] = ('pic', (a + 4 + im.u32(lit)) & 0xffffffff, a)
    for a in words:
        if a - 4 not in words:
            align[a] = 4
    for a in lab:
        if a >= TAIL and a % 4 == 0:
            align.setdefault(a, 8 if a % 8 == 0 and a >= 0x74a8 and a < REGION_TABLE[0] else 4)

    occupied = {}
    for a, i in im.ins.items():
        for k in range(i.size):
            occupied[a + k] = a
    for a in words:
        for k in range(4):
            assert a + k not in occupied, hex(a)
            occupied[a + k] = a
    for a in lab:
        assert occupied.get(a, a) == a, 'label inside object %x' % a

    (OUT / 'dsp').mkdir(parents=True, exist_ok=True)
    o = ['@ Generated by kit/split.py from %s -- edit, then run kit/build.py' % Path(im_path(im)).name,
         '.syntax unified', '.cpu cortex-m0', '.thumb', '.text',
         '.macro PTR e:vararg', '    .long \\e', '.endm',
         '#define ABS(sym) ((sym) - _image_base + 0x%x)' % BASE,
         '_image_base:']
    dsp_start = {s: (n, e) for n, (s, e) in DSP.items()}
    ALL, items = '--label-all' in sys.argv, {}
    a, end = BASE, im.end
    ins_end = {x + i.size for x, i in im.ins.items()}
    while a < end:
        # padding that exists only to align the next object
        nxt = next((t for t in (a + 2, a + 6) if t in align), None)
        if a in KNOWN_PADS or (nxt == a + 2 and a % 4 == 2 and a not in occupied and a + 1 not in occupied
                               and a not in lab and im.u16(a) == 0 and a in ins_end):
            a = (a + 6 if a in KNOWN_PADS else a + 2)
            continue
        if a in align:
            o.append('    .balignw %d, 0' % align[a])   # 2-byte fill: LLVM < 20 turns a 1-byte zero fill into NOPs in code
        if a in lab:
            o.append('%s:' % lab[a])
        if ALL:
            o.append('i_%04x:' % a)
            items[a] = (['ins'] if a in im.ins else ['word'] + list(wkind.get(a, ('const',))) if a in words else ['raw'])
        if a in im.ins:
            i = im.ins[a]
            t = i.text
            if '{T}' in t:
                t = t.replace('{T}', lab[i.target])
            if i.text.startswith('.inst.n 0x447'):
                t += '        @ add r%d, pc' % (int(i.text[-1], 16) & 7)
            o.append('    %-40s @ %04x' % (t, a))
            a += i.size
            if a in im.switch:
                n, tg = im.switch[a]
                o.append('switch_%04x:' % a)
                o.append('    .byte %d' % n)
                for t in tg:
                    o.append('    .byte (%s - switch_%04x) / 2' % (L(t, 'loc'), a))
                a += n + 2
                if a % 2:
                    o.append('    .byte 0x%02x' % im.u8(a)); a += 1
            continue
        if a in words:
            o.append('    PTR %-36s @ %04x = %08x' % (words[a], a, im.u32(a)))
            a += 4
            continue
        if a in dsp_start:
            n, e = dsp_start[a]
            (OUT / 'dsp' / (n + '.bin')).write_bytes(im.data[a - BASE:e - BASE])
            o.append('    .incbin "dsp/%s.bin"' % n)
            o.append('dsp_%s_end:' % n)
            a = e
            continue
        # raw bytes up to the next classified address
        e = a + 1
        while e < end and e not in occupied and e not in lab and e not in dsp_start and e not in KNOWN_PADS \
                and not (e % 4 == 2 and e + 2 in align and e in ins_end and im.u16(e) == 0):
            e += 1
        blob = im.data[a - BASE:e - BASE]
        if len(blob) == 2 and a % 2 == 0:
            o.append('    .short 0x%04x %28s @ %04x (unreferenced)' % (im.u16(a), '', a))
        else:
            for k in range(0, len(blob), 16):
                o.append('    .byte ' + ', '.join('0x%02x' % b for b in blob[k:k + 16]))
        a = e
    o.append('_image_end:')
    if ALL:
        o.append('i_%04x:' % end)
        import json
        (OUT / 'items.json').write_text(json.dumps({'items': items, 'switch': {k: v[1] for k, v in im.switch.items()}}))
    (OUT / 'app.S').write_text('\n'.join(o) + '\n')
    print('wrote %s: %d lines, %d labels, %d symbolic words' %
          (OUT / 'app.S', len(o), len(lab), sum(1 for w in words.values() if not w.startswith('0x'))))


def im_path(im):
    a = [x for x in sys.argv[1:] if not x.startswith('--')]
    return a[0] if a else FW


if __name__ == '__main__':
    main()
